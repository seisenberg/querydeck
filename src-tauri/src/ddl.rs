use crate::catalog::TableInfo;
use crate::drivers::Dialect;

/// Generate CREATE TABLE DDL from catalog metadata. Used when the engine has
/// no native DDL dump (PostgreSQL tables, ODBC, JDBC).
pub fn generate_table_ddl(dialect: Dialect, schema: &str, table: &TableInfo) -> String {
    let q = |s: &str| dialect.quote_ident(s);
    let qualified = if schema.is_empty() || schema == "main" || schema == "(default)" {
        q(&table.name)
    } else {
        format!("{}.{}", q(schema), q(&table.name))
    };

    let mut lines: Vec<String> = Vec::new();
    let col_width = table
        .columns
        .iter()
        .map(|c| q(&c.name).len())
        .max()
        .unwrap_or(0);

    for c in &table.columns {
        let mut line = format!("    {:<w$} {}", q(&c.name), c.data_type, w = col_width);
        if !c.nullable {
            line.push_str(" NOT NULL");
        }
        if let Some(d) = &c.default {
            line.push_str(&format!(" DEFAULT {d}"));
        }
        lines.push(line);
    }

    if !table.pk.is_empty() {
        let cols: Vec<String> = table.pk.iter().map(|c| q(c)).collect();
        lines.push(format!("    PRIMARY KEY ({})", cols.join(", ")));
    }
    for fk in &table.foreign_keys {
        lines.push(format!("    {fk}"));
    }

    let mut ddl = format!("CREATE TABLE {qualified} (\n{}\n);", lines.join(",\n"));

    // Skip the PK's implicit index; emit the rest as-is (they arrive as
    // complete statements, e.g. from pg_indexes).
    let extra: Vec<&String> = table
        .indexes
        .iter()
        .filter(|ix| !ix.contains("_pkey") || !ix.to_uppercase().contains("UNIQUE INDEX"))
        .collect();
    if !extra.is_empty() {
        ddl.push_str("\n\n");
        for ix in extra {
            let ix = ix.trim().trim_end_matches(';');
            ddl.push_str(&format!("{ix};\n"));
        }
    }
    ddl
}

/// DDL header comment shown in the viewer.
pub fn ddl_comment(engine_native: bool) -> &'static str {
    if engine_native {
        "-- Definition as reported by the database engine\n"
    } else {
        "-- Definition generated by QueryDeck from catalog metadata\n-- (approximate; may omit engine-specific options)\n"
    }
}
